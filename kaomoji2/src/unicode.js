  function block(cp) {
    var lo = 0, hi = BLOCKS.length - 1;
    while (lo <= hi) {
      var mid = (lo + hi) >> 1, b = BLOCKS[mid];
      if (cp < b[0]) hi = mid - 1;
      else if (cp > b[1]) lo = mid + 1;
      else return b;
    }
    return null;
  }

  /* 0 常见；1 大部分新手机都有；2 不少设备会显示成方框 □ */
  function level(text) {
    var lv = 0;
    for (var ch of text) {
      var b = block(ch.codePointAt(0));
      var l = b ? b[4] : 1;
      if (l > lv) lv = l;
      if (lv === 2) break;
    }
    return lv;
  }

  function isMark(cp) {
    return (cp >= 0x0300 && cp <= 0x036F) || (cp >= 0x1AB0 && cp <= 0x1AFF) ||
      (cp >= 0x1DC0 && cp <= 0x1DFF) || (cp >= 0x20D0 && cp <= 0x20FF) ||
      (cp >= 0xFE20 && cp <= 0xFE2F) || cp === 0x200D || (cp >= 0xFE00 && cp <= 0xFE0F) ||
      MARKS.test(String.fromCodePoint(cp));
  }
  var MARKS = /\p{M}/u;

  function isWide(cp) {
    return (cp >= 0x1100 && cp <= 0x115F) || (cp >= 0x2E80 && cp <= 0x303E) ||
      (cp >= 0x3041 && cp <= 0x33FF) || (cp >= 0x3400 && cp <= 0x4DBF) ||
      (cp >= 0x4E00 && cp <= 0x9FFF) || (cp >= 0xA000 && cp <= 0xA4CF) ||
      (cp >= 0xAC00 && cp <= 0xD7A3) || (cp >= 0xF900 && cp <= 0xFAFF) ||
      (cp >= 0xFE30 && cp <= 0xFE4F) || (cp >= 0xFF00 && cp <= 0xFF60) ||
      (cp >= 0xFFE0 && cp <= 0xFFE6) || (cp >= 0x13000 && cp <= 0x1342F) ||
      (cp >= 0x1F300 && cp <= 0x1FAFF) || (cp >= 0x20000 && cp <= 0x3FFFD);
  }

  /* 中文字体里会画成全角的“两可”字符：制表符、圆圈、星星这些 */
  function isAmbiguous(cp) {
    return (cp >= 0x2500 && cp <= 0x257F) || (cp >= 0x25A0 && cp <= 0x25FF) ||
      (cp >= 0x2600 && cp <= 0x26FF) || cp === 0x00B0 || cp === 0x00D7 ||
      (cp >= 0x2190 && cp <= 0x21FF) || (cp >= 0x2200 && cp <= 0x22FF);
  }

  /* 显示宽度：半角 1，全角 2。amb 是“两可”字符算多宽（中文聊天软件里一般按 2） */
  function width(text, amb) {
    if (amb == null) amb = 1;
    var w = 0;
    for (var ch of text) {
      var cp = ch.codePointAt(0);
      if (isMark(cp)) continue;
      w += isWide(cp) ? 2 : isAmbiguous(cp) ? amb : 1;
    }
    return w;
  }

  /* 按“字”切开：一个底字带上它后面的组合符号 */
  function graphemes(text) {
    if (typeof Intl !== "undefined" && Intl.Segmenter) {
      var seg = new Intl.Segmenter("zh", { granularity: "grapheme" });
      return Array.from(seg.segment(text), function (s) { return s.segment; });
    }
    var out = [];
    for (var ch of text) {
      if (out.length && isMark(ch.codePointAt(0))) out[out.length - 1] += ch;
      else out.push(ch);
    }
    return out;
  }

